#!/usr/bin/env node
// Regenerates packages/content/src/aws/manifest.ts by scanning clf-c02/ and saa-c03/.

import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const AWS_DIR = join(__dirname, '..', 'packages', 'content', 'src', 'aws');
const CERTS = ['clf-c02', 'saa-c03'];

const imports = [];
const names = [];

for (const cert of CERTS) {
  const certDir = join(AWS_DIR, cert);
  if (!existsSync(certDir)) continue;
  const files = readdirSync(certDir).filter((f) => f.endsWith('.json')).sort();
  for (const file of files) {
    const orderMatch = file.match(/^sim-(\d+)-/);
    if (!orderMatch) continue;
    const certVar = cert.replace(/-/g, '_');
    const name = `sim_${certVar}_${orderMatch[1]}`;
    imports.push(`import ${name} from './${cert}/${file}' with { type: 'json' };`);
    names.push(name);
  }
}

const content = `// Auto-generated by scripts/regen-aws-manifest.mjs — do not edit by hand.

${imports.join('\n')}

export const AWS_SIMULATIONS_RAW: unknown[] = [
${names.map((n) => `  ${n},`).join('\n')}
];
`;

writeFileSync(join(AWS_DIR, 'manifest.ts'), content, 'utf8');
console.log(`Wrote ${names.length} simulations to manifest.ts`);
