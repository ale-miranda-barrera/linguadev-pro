#!/usr/bin/env node
// Regenerates packages/content/src/packs/levels/index.ts by scanning subdirs.
// Runs after subagents finish writing JSON packs.

import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const LEVELS_DIR = join(__dirname, '..', 'packages', 'content', 'src', 'packs', 'levels');
const BANDS = ['a2', 'a2plus', 'b1', 'b2', 'b2plus'];

if (!existsSync(LEVELS_DIR)) {
  console.error('Levels directory not found:', LEVELS_DIR);
  process.exit(1);
}

const imports = [];
const names = [];

for (const band of BANDS) {
  const bandDir = join(LEVELS_DIR, band);
  if (!existsSync(bandDir)) continue;
  const files = readdirSync(bandDir).filter((f) => f.endsWith('.json')).sort();
  for (const file of files) {
    // 01-greetings-introductions.json → a2_01
    const orderMatch = file.match(/^(\d+)-/);
    if (!orderMatch) continue;
    const name = `${band}_${orderMatch[1]}`;
    imports.push(`import ${name} from './${band}/${file}' with { type: 'json' };`);
    names.push(name);
  }
}

const content = `// Auto-generated by scripts/regen-level-manifest.mjs — do not edit by hand.
// Regenerate: node scripts/regen-level-manifest.mjs

${imports.join('\n')}

export const LEVEL_PACKS: unknown[] = [
${names.map((n) => `  ${n},`).join('\n')}
];
`;

const outPath = join(LEVELS_DIR, 'index.ts');
writeFileSync(outPath, content, 'utf8');
console.log(`Wrote ${names.length} packs to ${outPath}`);
